// Lists every {% todo %} and {% proposed %} in src/ and writes TODO.md.
// Run: npm run todos
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const root = "src";
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === "_includes") continue; // templates, not content
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(md|njk|js)$/.test(name)) files.push(p);
  }
})(root);

const rows = [];
for (const file of files) {
  const lines = readFileSync(file, "utf8").split("\n");
  lines.forEach((line, i) => {
    const rel = relative(".", file).replaceAll("\\", "/");
    for (const m of line.matchAll(/\{%-?\s*todo\s+"([^"]+)"/g)) rows.push(`- [ ] \`${rel}:${i + 1}\`: ${m[1]}`);
    if (/\{%-?\s*proposed\s*-?%\}/.test(line) || /ledeProposed:\s*true|summaryProposed:\s*true|copyProposed:\s*true/.test(line))
      rows.push(`- [ ] \`${rel}:${i + 1}\`: proposed copy, needs Aaron's OK`);
    if (/^draft:\s*true/.test(line)) rows.push(`- [ ] \`${rel}\`: page is a draft (not published)`);
    if (/image:\s*""/.test(line)) rows.push(`- [ ] \`${rel}:${i + 1}\`: card cover image missing`);
    if (/summary:\s*""/.test(line)) rows.push(`- [ ] \`${rel}:${i + 1}\`: card summary missing`);
  });
}

writeFileSync(
  "TODO.md",
  `# TODO\n\nGenerated by \`npm run todos\`. Don't edit by hand; fix the item in the file it points to, then rerun.\n\n${rows.join("\n")}\n`
);
console.log(`${rows.length} open items written to TODO.md`);
